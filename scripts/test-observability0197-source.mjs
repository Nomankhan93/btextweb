import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = (path) => fs.readFileSync(path, 'utf8')
const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const observability = read('src/lib/observability.ts')
const errors = read('src/lib/errors.ts')
const main = read('src/main.tsx')
const app = read('src/App.tsx')
const boundary = read('src/components/AppErrorBoundary.tsx')
const settings = read('src/pages/SettingsPage.tsx')
const draftStorage = read('src/lib/campaignDraftStorage.ts')
const tests = read('src/test/observability0197.test.ts')
const preflight = read('scripts/preflight.mjs')
const sw = read('public/service-worker.js')

let assertions = 0
function check(condition, message) {
  assertions += 1
  assert.ok(condition, message)
}

check(pkg.version === '0.20.1', 'frontend version must be 0.20.1')
check(pkg.bulktext?.backendContractVersion === '0.18.5', 'backend contract must remain 0.18.5')
check(lock.version === '0.20.1' && lock.packages?.['']?.version === '0.20.1', 'package-lock release version must match package.json')
check(pkg.scripts?.['test:observability-source-0197'] === 'node scripts/test-observability0197-source.mjs', 'source contract command must exist')
check(pkg.scripts?.['test:observability-0197']?.includes('src/test/observability0197.test.ts'), 'focused observability Vitest command must exist')
check(observability.includes("OBSERVABILITY_RELEASE = '0.20.1'"), 'diagnostic events must carry the 0.20.1 release marker')
check(observability.includes("STORAGE_KEY = 'bulktext:diagnostics:v1'"), 'diagnostic storage must use a dedicated namespaced key')
check(observability.includes('MAX_EVENTS = 25'), 'diagnostic buffer must be bounded to 25 events')
check(observability.includes("'handled-error'"), 'handled failures must be representable')
check(observability.includes("'window-error'"), 'window errors must be representable')
check(observability.includes("'unhandled-rejection'"), 'unhandled promise rejections must be representable')
check(observability.includes("'react-render'"), 'React render failures must be representable')
check(observability.includes("'route-load'"), 'route chunk/render failures must be representable')
check(observability.includes('safeToken'), 'diagnostic name/code/status values must be constrained')
check(observability.includes('currentRouteGroup'), 'diagnostics must use coarse route groups rather than raw paths')
check(!observability.includes('window.location.href'), 'full URLs must not be persisted')
check(!observability.includes('window.location.search'), 'query strings must not be persisted')
check(!observability.includes('user.email'), 'user email must not be persisted')
check(!observability.includes('localStorage'), 'diagnostic events must not be persisted beyond the current tab session')
check(observability.includes('sessionStorage'), 'diagnostic events must use session-scoped storage')
check(observability.includes("window.addEventListener('error'"), 'global window errors must be captured')
check(observability.includes("window.addEventListener('unhandledrejection'"), 'global unhandled rejections must be captured')
check(errors.includes("reportDiagnostic(context, { source: 'handled-error'"), 'safe error boundary must report classified operational failures')
check(errors.includes("if (category !== 'domain')"), 'expected domain validation messages must not create observability noise')
check(errors.includes('statusNumber >= 500'), 'server failures must be treated as internal failures')
check(main.includes('installGlobalObservability()'), 'global observability must be installed before app rendering')
check(main.includes('<AppErrorBoundary>'), 'top-level render tree must have a fatal render boundary')
check(boundary.includes("source: 'react-render'"), 'top-level render failures must be reported')
check(boundary.includes('A technical error was recorded without message content or account data.'), 'fatal fallback must explain the privacy-safe diagnostic behavior')
check(app.includes("source: 'route-load'"), 'lazy route failures must be reported')
check(settings.includes('Technical diagnostics'), 'Settings must expose support diagnostics')
check(settings.includes('Copy diagnostics'), 'Settings must allow sanitized diagnostic export')
check(settings.includes('Clear diagnostics'), 'Settings must allow diagnostic cleanup')
check(settings.includes('phone numbers, contact data, auth tokens, query strings, backend details and hints are not stored'), 'Settings must disclose diagnostic privacy boundaries')
check(settings.includes("errorMessage(updateError, 'Could not update your profile.')"), 'Settings profile failures must use safe error presentation')
check(!draftStorage.includes('reason instanceof Error ? reason.message'), 'offline draft storage must not surface raw browser exception messages')
check(draftStorage.includes("reportDiagnostic(reason, { source: 'handled-error', category: 'internal'"), 'offline draft storage failures must report sanitized internal diagnostics')
check(tests.includes('records handled backend failures without storing raw message, details or hint text'), 'raw diagnostic leakage regression must be covered')
check(tests.includes('does not record expected user-safe domain validation messages'), 'domain-noise regression must be covered')
check(tests.includes('keeps only the latest 25 sanitized events'), 'bounded-buffer regression must be covered')
check(tests.includes('exports a support snapshot containing sanitized events only'), 'support export regression must be covered')
check(preflight.includes('test-observability0197-source.mjs'), 'preflight must require the 0.20.1 observability source contract')
check(sw.includes("const VERSION = '0.20.1'"), 'service-worker cache marker must match 0.20.1')
check(!fs.existsSync('supabase/migrations/20261012001970_production_observability.sql'), '0.20.1 must not add a database migration')

console.log(`Web 0.20.1 production observability source contract: PASS (${assertions} assertions)`)
