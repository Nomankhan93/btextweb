create or replace function public.contact_compliance_state_internal(
  p_organization_id uuid,
  p_normalized_e164 text
)
returns table(
  normalized_e164 text,
  consent_state text,
  consent_event_id bigint,
  consent_source text,
  consent_occurred_at timestamptz,
  consent_expires_at timestamptz,
  suppression_state text,
  suppression_event_id bigint,
  suppression_reason text,
  suppression_source text,
  suppression_occurred_at timestamptz,
  eligibility_state text,
  block_reason text
)
language sql
stable
security definer
set search_path = public
as $$
  with latest_consent as (
    select e.*
    from public.contact_consent_events e
    where e.organization_id = p_organization_id
      and e.normalized_e164 = p_normalized_e164
    order by e.occurred_at desc, e.id desc
    limit 1
  ), latest_suppression as (
    select e.*
    from public.contact_suppression_events e
    where e.organization_id = p_organization_id
      and e.normalized_e164 = p_normalized_e164
    order by e.occurred_at desc, e.id desc
    limit 1
  ), state as (
    select
      p_normalized_e164 as normalized_e164,
      case
        when c.id is null then 'none'
        when c.event_type = 'revoked' then 'revoked'
        when c.expires_at is not null and c.expires_at <= now() then 'expired'
        else 'granted'
      end as consent_state,
      c.id as consent_event_id,
      c.source as consent_source,
      c.occurred_at as consent_occurred_at,
      c.expires_at as consent_expires_at,
      case when s.event_type = 'suppressed' then 'suppressed' else 'clear' end as suppression_state,
      s.id as suppression_event_id,
      case when s.event_type = 'suppressed' then s.reason else null end as suppression_reason,
      s.source as suppression_source,
      s.occurred_at as suppression_occurred_at
    from (select 1) seed
    left join latest_consent c on true
    left join latest_suppression s on true
  )
  select
    st.normalized_e164,
    st.consent_state,
    st.consent_event_id,
    st.consent_source,
    st.consent_occurred_at,
    st.consent_expires_at,
    st.suppression_state,
    st.suppression_event_id,
    st.suppression_reason,
    st.suppression_source,
    st.suppression_occurred_at,
    case
      when st.suppression_state = 'suppressed' then 'blocked'
      when st.consent_state = 'granted' then 'eligible'
      else 'blocked'
    end as eligibility_state,
    case
      when st.suppression_state = 'suppressed' then 'suppressed'
      when st.consent_state = 'none' then 'no_consent'
      when st.consent_state = 'revoked' then 'consent_revoked'
      when st.consent_state = 'expired' then 'consent_expired'
      else null
    end as block_reason
  from state st;
$$;

create or replace function public.record_contact_consent(
  p_organization_id uuid,
  p_phone text,
  p_event_type text,
  p_source text,
  p_evidence_note text default null,
  p_evidence_reference text default null,
  p_occurred_at timestamptz default null,
  p_expires_at timestamptz default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_normalized text;
  v_status text;
  v_reason text;
  v_event_id bigint;
  v_occurred_at timestamptz := coalesce(p_occurred_at, now());
  v_note text := nullif(trim(coalesce(p_evidence_note, '')), '');
  v_reference text := nullif(trim(coalesce(p_evidence_reference, '')), '');
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.can_manage_contact_compliance(p_organization_id) then
    raise exception 'Owner, Admin or Campaign Manager permission required to manage consent' using errcode = '42501';
  end if;

  if p_event_type is null or p_event_type not in ('granted', 'revoked') then
    raise exception 'Consent event type must be granted or revoked' using errcode = '22023';
  end if;

  if p_source is null or p_source not in ('web_form', 'paper_form', 'verbal', 'import', 'api', 'manual', 'other') then
    raise exception 'Unsupported consent source' using errcode = '22023';
  end if;

  if v_note is null and v_reference is null then
    raise exception 'Consent evidence note or reference is required' using errcode = '22023';
  end if;

  if char_length(coalesce(v_note, '')) > 1000 or char_length(coalesce(v_reference, '')) > 500 then
    raise exception 'Consent evidence is too long' using errcode = '22023';
  end if;

  if v_occurred_at > now() + interval '5 minutes' then
    raise exception 'Consent event time cannot be in the future' using errcode = '22023';
  end if;

  if p_event_type = 'revoked' and p_expires_at is not null then
    raise exception 'Revoked consent cannot have an expiry time' using errcode = '22023';
  end if;

  if p_event_type = 'granted' and p_expires_at is not null and p_expires_at <= v_occurred_at then
    raise exception 'Consent expiry must be after the grant time' using errcode = '22023';
  end if;

  select normalized_e164, validation_status, validation_reason
    into v_normalized, v_status, v_reason
  from public.normalize_phone_number(p_phone, 'PK')
  limit 1;

  if v_status <> 'valid' or v_normalized is null then
    raise exception 'A valid Pakistan mobile number is required: %', v_reason using errcode = '22023';
  end if;

  insert into public.contact_consent_events (
    organization_id, normalized_e164, event_type, source, evidence_note,
    evidence_reference, occurred_at, expires_at, recorded_by
  ) values (
    p_organization_id, v_normalized, p_event_type, p_source, v_note,
    v_reference, v_occurred_at, case when p_event_type = 'granted' then p_expires_at else null end, v_actor
  ) returning id into v_event_id;

  insert into public.audit_logs (
    organization_id, actor_user_id, action, target_type, target_id, metadata
  ) values (
    p_organization_id,
    v_actor,
    case when p_event_type = 'granted' then 'contacts.consent_granted' else 'contacts.consent_revoked' end,
    'contact_consent_event',
    v_event_id::text,
    jsonb_build_object(
      'normalizedE164', v_normalized,
      'source', p_source,
      'occurredAt', v_occurred_at,
      'expiresAt', case when p_event_type = 'granted' then p_expires_at else null end
    )
  );

  return v_event_id;
end;
$$;

create or replace function public.record_contact_suppression(
  p_organization_id uuid,
  p_phone text,
  p_event_type text,
  p_reason text default null,
  p_source text default 'manual',
  p_note text default null,
  p_occurred_at timestamptz default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_normalized text;
  v_status text;
  v_reason_text text;
  v_event_id bigint;
  v_occurred_at timestamptz := coalesce(p_occurred_at, now());
  v_note text := nullif(trim(coalesce(p_note, '')), '');
  v_latest_event text;
  v_latest_time timestamptz;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.can_manage_contact_compliance(p_organization_id) then
    raise exception 'Owner, Admin or Campaign Manager permission required to manage suppression' using errcode = '42501';
  end if;

  if p_event_type is null or p_event_type not in ('suppressed', 'lifted') then
    raise exception 'Suppression event type must be suppressed or lifted' using errcode = '22023';
  end if;

  if p_event_type = 'lifted' and not public.can_lift_contact_suppressions(p_organization_id) then
    raise exception 'Only Owner or Admin can lift a suppression' using errcode = '42501';
  end if;

  if p_source is null or p_source not in ('recipient_reply', 'import', 'api', 'manual', 'other') then
    raise exception 'Unsupported suppression source' using errcode = '22023';
  end if;

  if p_event_type = 'suppressed' and (p_reason is null or p_reason not in ('opt_out', 'complaint', 'manual', 'regulatory', 'other')) then
    raise exception 'A valid suppression reason is required' using errcode = '22023';
  end if;

  if p_event_type = 'lifted' and (p_reason is not null or v_note is null) then
    raise exception 'Lifting suppression requires a note and no suppression reason' using errcode = '22023';
  end if;

  if char_length(coalesce(v_note, '')) > 1000 then
    raise exception 'Suppression note is too long' using errcode = '22023';
  end if;

  if v_occurred_at > now() + interval '5 minutes' then
    raise exception 'Suppression event time cannot be in the future' using errcode = '22023';
  end if;

  select normalized_e164, validation_status, validation_reason
    into v_normalized, v_status, v_reason_text
  from public.normalize_phone_number(p_phone, 'PK')
  limit 1;

  if v_status <> 'valid' or v_normalized is null then
    raise exception 'A valid Pakistan mobile number is required: %', v_reason_text using errcode = '22023';
  end if;

  select e.event_type, e.occurred_at
    into v_latest_event, v_latest_time
  from public.contact_suppression_events e
  where e.organization_id = p_organization_id
    and e.normalized_e164 = v_normalized
  order by e.occurred_at desc, e.id desc
  limit 1;

  if p_event_type = 'suppressed' and v_latest_event = 'suppressed' then
    raise exception 'This number is already suppressed' using errcode = '22023';
  end if;

  if p_event_type = 'lifted' and v_latest_event is distinct from 'suppressed' then
    raise exception 'This number is not currently suppressed' using errcode = '22023';
  end if;

  if v_latest_time is not null and v_occurred_at < v_latest_time then
    raise exception 'Suppression state changes cannot be backdated before the current state event' using errcode = '22023';
  end if;

  insert into public.contact_suppression_events (
    organization_id, normalized_e164, event_type, reason, source, note, occurred_at, recorded_by
  ) values (
    p_organization_id,
    v_normalized,
    p_event_type,
    case when p_event_type = 'suppressed' then p_reason else null end,
    p_source,
    v_note,
    v_occurred_at,
    v_actor
  ) returning id into v_event_id;

  insert into public.audit_logs (
    organization_id, actor_user_id, action, target_type, target_id, metadata
  ) values (
    p_organization_id,
    v_actor,
    case when p_event_type = 'suppressed' then 'contacts.suppressed' else 'contacts.suppression_lifted' end,
    'contact_suppression_event',
    v_event_id::text,
    jsonb_build_object(
      'normalizedE164', v_normalized,
      'reason', case when p_event_type = 'suppressed' then p_reason else null end,
      'source', p_source,
      'occurredAt', v_occurred_at
    )
  );

  return v_event_id;
end;
$$;

create or replace function public.get_contact_compliance_status(
  p_organization_id uuid,
  p_phone text
)
returns table(
  normalized_e164 text,
  consent_state text,
  consent_event_id bigint,
  consent_source text,
  consent_occurred_at timestamptz,
  consent_expires_at timestamptz,
  suppression_state text,
  suppression_event_id bigint,
  suppression_reason text,
  suppression_source text,
  suppression_occurred_at timestamptz,
  eligibility_state text,
  block_reason text
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_normalized text;
  v_status text;
  v_reason text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.is_org_member(p_organization_id) then
    raise exception 'Organization membership required' using errcode = '42501';
  end if;

  select n.normalized_e164, n.validation_status, n.validation_reason
    into v_normalized, v_status, v_reason
  from public.normalize_phone_number(p_phone, 'PK') n
  limit 1;

  if v_status <> 'valid' or v_normalized is null then
    raise exception 'A valid Pakistan mobile number is required: %', v_reason using errcode = '22023';
  end if;

  return query
  select * from public.contact_compliance_state_internal(p_organization_id, v_normalized);
end;
$$;

create or replace function public.list_contact_compliance_statuses(
  p_organization_id uuid,
  p_limit integer default 100
)
returns table(
  normalized_e164 text,
  consent_state text,
  consent_event_id bigint,
  consent_source text,
  consent_occurred_at timestamptz,
  consent_expires_at timestamptz,
  suppression_state text,
  suppression_event_id bigint,
  suppression_reason text,
  suppression_source text,
  suppression_occurred_at timestamptz,
  eligibility_state text,
  block_reason text
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.is_org_member(p_organization_id) then
    raise exception 'Organization membership required' using errcode = '42501';
  end if;

  if p_limit is null or p_limit < 1 or p_limit > 500 then
    raise exception 'Limit must be between 1 and 500' using errcode = '22023';
  end if;

  return query
  with phones as (
    select e.normalized_e164, max(e.created_at) as last_recorded_at
    from public.contact_consent_events e
    where e.organization_id = p_organization_id
    group by e.normalized_e164
    union
    select e.normalized_e164, max(e.created_at) as last_recorded_at
    from public.contact_suppression_events e
    where e.organization_id = p_organization_id
    group by e.normalized_e164
  ), ranked as (
    select p.normalized_e164, max(p.last_recorded_at) as last_recorded_at
    from phones p
    group by p.normalized_e164
    order by max(p.last_recorded_at) desc, p.normalized_e164
    limit p_limit
  )
  select s.*
  from ranked r
  cross join lateral public.contact_compliance_state_internal(p_organization_id, r.normalized_e164) s
  order by r.last_recorded_at desc, r.normalized_e164;
end;
$$;

create or replace function public.list_contact_compliance_history(
  p_organization_id uuid,
  p_phone text
)
returns table(
  event_kind text,
  event_id bigint,
  event_type text,
  source text,
  reason text,
  detail text,
  evidence_reference text,
  occurred_at timestamptz,
  expires_at timestamptz,
  recorded_by uuid,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_normalized text;
  v_status text;
  v_reason text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.can_manage_contact_compliance(p_organization_id) then
    raise exception 'Owner, Admin or Campaign Manager permission required to inspect compliance evidence' using errcode = '42501';
  end if;

  select n.normalized_e164, n.validation_status, n.validation_reason
    into v_normalized, v_status, v_reason
  from public.normalize_phone_number(p_phone, 'PK') n
  limit 1;

  if v_status <> 'valid' or v_normalized is null then
    raise exception 'A valid Pakistan mobile number is required: %', v_reason using errcode = '22023';
  end if;

  return query
  select *
  from (
    select
      'consent'::text as event_kind,
      c.id as event_id,
      c.event_type,
      c.source,
      null::text as reason,
      c.evidence_note as detail,
      c.evidence_reference,
      c.occurred_at,
      c.expires_at,
      c.recorded_by,
      c.created_at
    from public.contact_consent_events c
    where c.organization_id = p_organization_id and c.normalized_e164 = v_normalized

    union all

    select
      'suppression'::text,
      s.id,
      s.event_type,
      s.source,
      s.reason,
      s.note,
      null::text,
      s.occurred_at,
      null::timestamptz,
      s.recorded_by,
      s.created_at
    from public.contact_suppression_events s
    where s.organization_id = p_organization_id and s.normalized_e164 = v_normalized
  ) events
  order by events.occurred_at desc, events.created_at desc, events.event_id desc;
end;
$$;

create table if not exists public.recipient_eligibility_snapshots (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  recipient_preview_id uuid not null references public.recipient_previews(id) on delete cascade,
  created_by uuid references public.profiles(id) on delete set null,
  revision integer not null check (revision > 0),
  policy_version text not null default 'consent-suppression-v1' check (policy_version = 'consent-suppression-v1'),
  candidate_rows integer not null default 0 check (candidate_rows >= 0),
  eligible_rows integer not null default 0 check (eligible_rows >= 0),
  no_consent_rows integer not null default 0 check (no_consent_rows >= 0),
  consent_revoked_rows integer not null default 0 check (consent_revoked_rows >= 0),
  consent_expired_rows integer not null default 0 check (consent_expired_rows >= 0),
  suppressed_rows integer not null default 0 check (suppressed_rows >= 0),
  created_at timestamptz not null default now(),
  unique (recipient_preview_id, revision),
  check (candidate_rows = eligible_rows + no_consent_rows + consent_revoked_rows + consent_expired_rows + suppressed_rows)
);

create index if not exists recipient_eligibility_snapshots_org_created_idx
