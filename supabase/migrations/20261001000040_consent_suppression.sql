  reason text check (reason in ('opt_out', 'complaint', 'manual', 'regulatory', 'other')),
  source text not null check (source in ('recipient_reply', 'import', 'api', 'manual', 'other')),
  note text,
  occurred_at timestamptz not null,
  recorded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  check (char_length(coalesce(note, '')) <= 1000),
  check (
    (event_type = 'suppressed' and reason is not null)
    or (event_type = 'lifted' and reason is null and char_length(trim(coalesce(note, ''))) > 0)
  )
);

