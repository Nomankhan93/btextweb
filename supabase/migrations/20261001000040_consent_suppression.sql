create or replace function public.create_recipient_eligibility_snapshot(
  p_organization_id uuid,
  p_preview_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_snapshot_id uuid;
  v_revision integer;
  v_candidates integer;
  v_eligible integer;
  v_no_consent integer;
  v_revoked integer;
  v_expired integer;
  v_suppressed integer;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not public.can_manage_contact_compliance(p_organization_id) then
    raise exception 'Owner, Admin or Campaign Manager permission required to create eligibility snapshots' using errcode = '42501';
  end if;

  perform 1
  from public.recipient_previews p
  where p.id = p_preview_id
    and p.organization_id = p_organization_id
  for update;

  if not found then
    raise exception 'Recipient preview not found' using errcode = 'P0002';
  end if;

  if not exists (
    select 1 from public.recipient_preview_rows r
    where r.preview_id = p_preview_id
      and r.organization_id = p_organization_id
      and r.decision = 'included'
  ) then
    raise exception 'Recipient preview has no included candidates' using errcode = '22023';
  end if;

  select coalesce(max(s.revision), 0) + 1
    into v_revision
  from public.recipient_eligibility_snapshots s
  where s.recipient_preview_id = p_preview_id;

  insert into public.recipient_eligibility_snapshots (
    organization_id, recipient_preview_id, created_by, revision
  ) values (
    p_organization_id, p_preview_id, v_actor, v_revision
  ) returning id into v_snapshot_id;

  insert into public.recipient_eligibility_rows (
    snapshot_id, organization_id, recipient_preview_id, preview_row_id,
    source_row_number, display_name, normalized_e164, eligibility_state, block_reason,
    consent_state, consent_event_id, consent_source, consent_occurred_at, consent_expires_at,
    suppression_state, suppression_event_id, suppression_reason, suppression_source, suppression_occurred_at
  )
  select
    v_snapshot_id,
    p_organization_id,
    p_preview_id,
    r.id,
    r.source_row_number,
    r.display_name,
    r.normalized_e164,
    s.eligibility_state,
    s.block_reason,
    s.consent_state,
    s.consent_event_id,
    s.consent_source,
    s.consent_occurred_at,
    s.consent_expires_at,
    s.suppression_state,
    s.suppression_event_id,
    s.suppression_reason,
    s.suppression_source,
    s.suppression_occurred_at
  from public.recipient_preview_rows r
  cross join lateral public.contact_compliance_state_internal(p_organization_id, r.normalized_e164) s
  where r.preview_id = p_preview_id
    and r.organization_id = p_organization_id
    and r.decision = 'included'
  order by r.source_row_number, r.id;

  select
    count(*)::integer,
    count(*) filter (where eligibility_state = 'eligible')::integer,
    count(*) filter (where block_reason = 'no_consent')::integer,
    count(*) filter (where block_reason = 'consent_revoked')::integer,
    count(*) filter (where block_reason = 'consent_expired')::integer,
    count(*) filter (where block_reason = 'suppressed')::integer
  into v_candidates, v_eligible, v_no_consent, v_revoked, v_expired, v_suppressed
  from public.recipient_eligibility_rows r
  where r.snapshot_id = v_snapshot_id;

  update public.recipient_eligibility_snapshots
  set candidate_rows = v_candidates,
      eligible_rows = v_eligible,
      no_consent_rows = v_no_consent,
      consent_revoked_rows = v_revoked,
      consent_expired_rows = v_expired,
      suppressed_rows = v_suppressed
  where id = v_snapshot_id;

  insert into public.audit_logs (
    organization_id, actor_user_id, action, target_type, target_id, metadata
  ) values (
    p_organization_id,
    v_actor,
    'contacts.eligibility_snapshot_created',
    'recipient_eligibility_snapshot',
    v_snapshot_id::text,
    jsonb_build_object(
      'recipientPreviewId', p_preview_id,
      'revision', v_revision,
      'candidateRows', v_candidates,
      'eligibleRows', v_eligible,
      'noConsentRows', v_no_consent,
      'consentRevokedRows', v_revoked,
      'consentExpiredRows', v_expired,
      'suppressedRows', v_suppressed,
      'policyVersion', 'consent-suppression-v1'
    )
  );

  return v_snapshot_id;
end;
$$;

