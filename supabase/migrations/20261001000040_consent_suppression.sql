create or replace function public.can_manage_contact_compliance(p_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.org_role(p_organization_id) in ('owner', 'admin', 'campaign_manager'), false);
$$;

create or replace function public.can_lift_contact_suppressions(p_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.org_role(p_organization_id) in ('owner', 'admin'), false);
$$;

create table if not exists public.contact_consent_events (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  normalized_e164 text not null check (normalized_e164 ~ '^\+923[0-9]{9}$'),
  event_type text not null check (event_type in ('granted', 'revoked')),
  source text not null check (source in ('web_form', 'paper_form', 'verbal', 'import', 'api', 'manual', 'other')),
  evidence_note text,
  evidence_reference text,
  occurred_at timestamptz not null,
  expires_at timestamptz,
  recorded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  check (char_length(coalesce(evidence_note, '')) <= 1000),
  check (char_length(coalesce(evidence_reference, '')) <= 500),
  check (
    char_length(trim(coalesce(evidence_note, ''))) > 0
    or char_length(trim(coalesce(evidence_reference, ''))) > 0
  ),
  check (
    (event_type = 'granted' and (expires_at is null or expires_at > occurred_at))
    or (event_type = 'revoked' and expires_at is null)
  )
);

create index if not exists contact_consent_events_org_phone_idx
