create table if not exists public.recipient_eligibility_rows (
  id bigint generated by default as identity primary key,
  snapshot_id uuid not null references public.recipient_eligibility_snapshots(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  recipient_preview_id uuid not null references public.recipient_previews(id) on delete cascade,
  preview_row_id bigint not null references public.recipient_preview_rows(id) on delete cascade,
  source_row_number integer not null check (source_row_number >= 2),
  display_name text,
  normalized_e164 text not null check (normalized_e164 ~ '^\+923[0-9]{9}$'),
  eligibility_state text not null check (eligibility_state in ('eligible', 'blocked')),
  block_reason text check (block_reason in ('no_consent', 'consent_revoked', 'consent_expired', 'suppressed')),
  consent_state text not null check (consent_state in ('none', 'granted', 'revoked', 'expired')),
  consent_event_id bigint references public.contact_consent_events(id) on delete set null,
  consent_source text,
  consent_occurred_at timestamptz,
  consent_expires_at timestamptz,
  suppression_state text not null check (suppression_state in ('clear', 'suppressed')),
  suppression_event_id bigint references public.contact_suppression_events(id) on delete set null,
  suppression_reason text,
  suppression_source text,
  suppression_occurred_at timestamptz,
  created_at timestamptz not null default now(),
  unique (snapshot_id, preview_row_id),
  check (
    (eligibility_state = 'eligible' and block_reason is null and consent_state = 'granted' and suppression_state = 'clear')
    or
    (eligibility_state = 'blocked' and block_reason is not null)
  )
);

create index if not exists recipient_eligibility_rows_snapshot_idx
  on public.recipient_eligibility_rows (snapshot_id, source_row_number);

create index if not exists recipient_eligibility_rows_org_phone_idx
  on public.recipient_eligibility_rows (organization_id, normalized_e164);

